import Foundation
import simd

/// A tangent-space box around the eye axis in the head frame (x right, y up): the tangent reach on each side,
/// positive away from the axis (left = -x, down = -y). Left/right are head-frame sides, as the client reports
/// fov tangents: L's left is temporal, R's left is nasal.
struct ProjectionBox: Equatable {
    let left, right, up, down: Double

    init(left: Double, right: Double, up: Double, down: Double) {
        self.left = left
        self.right = right
        self.up = up
        self.down = down
    }

    /// The rendered frustum (`m5_view` left, right, bottom, top).
    init(_ frustum: BoundaryDotsFrustum) {
        self.init(left: frustum.left, right: frustum.right, up: frustum.top, down: frustum.bottom)
    }

    var tangents: [Double] { [left, right, up, down] }
    var degrees: [Double] { tangents.map { atan($0) * 180 / .pi } }

    /// Closed path in tangent space, clockwise from the top-left corner, edges split into steps of at most `step`.
    /// Straight in tangent space is a great circle in the head frame, so the drawn edges are the box's.
    func path(step: Double) -> [SIMD2<Double>] {
        let corners: [SIMD2<Double>] = [[-left, up], [right, up], [right, -down], [-left, -down]]
        return corners.indices.flatMap { i -> [SIMD2<Double>] in
            let a = corners[i], b = corners[(i + 1) % corners.count]
            let count = max(1, Int((simd_distance(a, b) / step).rounded(.up)))
            return (0..<count).map { a + (b - a) * Double($0) / Double(count) }
        }
    }
}

/// One foveation setting: ALVR's `foveated_encoding` (FFR.swift FoveationSettings) and the render scale it was
/// planned with (per-eye render = render_scale x 3648x2912).
struct ProjectionFoveation: Equatable {
    let name: String
    let renderScale: Double
    let centerSize, shift, edgeRatio: SIMD2<Double>

    /// The fov_scale 1 rows of tools/fov-matrix/points-chart-avp.tsv at develop 6aab8e6 (22 Oct 2026, generated by
    /// avp-sharpness.py points): name, render_scale, foveation cx,cy,rx,ry,shx,shy. The fov_scale 0.85/0.7 rows
    /// render a smaller frustum than the one drawn here and are left out. Copied in tools/diag/fixtures/
    /// projection-points.json; test_projection_points_table.py checks this table against it and the tsv.
    static let points: [ProjectionFoveation] = [
        ("a100-asrun", 1, [0.5, 0.45, 3, 3, 0, 0]),
        ("a100-centred", 1, [0.5, 0.45, 3, 3, 0.293, -0.117]),
        ("a100-wider", 1, [0.563, 0.618, 2.5, 2.5, 0.335, -0.168]),
        ("a100-axis-C", 1.1447, [0.5, 0.45, 3, 3, 0.536, -0.159]),
        ("a100-axis-A", 1, [0.5, 0.45, 3, 3, 0.536, -0.159]),
        ("a100-wider-A", 0.8246, [0.563, 0.618, 2.5, 2.5, 0.335, -0.168]),
    ].map { (name: String, scale: Double, v: [Double]) in
        ProjectionFoveation(name: name, renderScale: scale, centerSize: [v[0], v[1]], shift: [v[4], v[5]], edgeRatio: [v[2], v[3]])
    }
    static let defaultName = "a100-axis-C"

    static func named(_ name: String) -> ProjectionFoveation? { points.first { $0.name == name } }

    /// cx,cy,rx,ry,shx,shy as in points-chart-avp.tsv.
    var text: String {
        [centerSize.x, centerSize.y, edgeRatio.x, edgeRatio.y, shift.x, shift.y]
            .map { String(format: "%g", locale: Locale(identifier: "en_US_POSIX"), $0) }.joined(separator: ",")
    }
}

/// Per-eye render size in pixels.
struct ProjectionRender: Equatable {
    static let base = (width: 3648, height: 2912)
    let width, height: Int

    init(width: Int, height: Int) {
        self.width = width
        self.height = height
    }

    /// render_scale x 3648x2912, rounded per side as tools/fov-matrix/fovmatrix.py render_size.
    init(scale: Double) {
        self.init(width: Int((Double(Self.base.width) * scale).rounded()), height: Int((Double(Self.base.height) * scale).rounded()))
    }
}

/// Where the foveation rect and px/deg come from: the live stream (its render size and FFR settings) or a points row.
struct ProjectionStream: Equatable {
    let source: String
    let foveation: ProjectionFoveation?
    let render: ProjectionRender
    /// The streaming session's settings; false for a compiled points row (a preset, shown when not streaming).
    let live: Bool

    static func points(_ row: ProjectionFoveation) -> ProjectionStream {
        ProjectionStream(source: row.name, foveation: row, render: ProjectionRender(scale: row.renderScale), live: false)
    }

    /// The streaming session's per-eye view size and raw `foveated_encoding` settings (nil: foveation off).
    static func live(width: Int, height: Int, centerSize: SIMD2<Double>?, shift: SIMD2<Double>?,
                     edgeRatio: SIMD2<Double>?) -> ProjectionStream {
        let foveation = centerSize.flatMap { size in shift.flatMap { shift in edgeRatio.map { ratio in
            ProjectionFoveation(name: "live", renderScale: Double(width) / Double(ProjectionRender.base.width),
                                centerSize: size, shift: shift, edgeRatio: ratio)
        } } }
        return ProjectionStream(source: "live", foveation: foveation, render: ProjectionRender(width: width, height: height), live: true)
    }
}

enum ProjectionOverlay {
    /// Eye hues at equal relative luminance (about 0.49): L cyan, R orange; white for the foveation rect and the
    /// cross in Both.
    static let white: SIMD3<Double> = [1, 1, 1]
    static func hue(_ eye: BoundaryDotsEye) -> SIMD3<Double> {
        switch eye {
        case .left: return [0, 0.79, 1]
        case .right: return [1, 0.66, 0]
        case .both: return white
        }
    }

    /// Relative luminance (Rec. 709 weights) of an sRGB colour.
    static func luminance(_ rgb: SIMD3<Double>) -> Double {
        func linear(_ c: Double) -> Double { c <= 0.04045 ? c / 12.92 : pow((c + 0.055) / 1.055, 2.4) }
        return 0.2126 * linear(rgb.x) + 0.7152 * linear(rgb.y) + 0.0722 * linear(rgb.z)
    }

    /// Ribbon widths in degrees: the frustum rectangle widest, the bbox thinnest.
    static let width = (frustum: 0.4, lens: BoundaryDotsOutline.lineWidthDeg, bbox: 0.15, foveation: 0.2, circle: 0.12)

    /// The bbox is drawn in short dashes (tangent length, about 1.1 deg near the axis) so a screenshot tells it from
    /// the solid frustum rectangle.
    static let bboxDash = (dash: 0.02, gap: 0.02)

    /// Splits a closed tangent-space path into dashes by length along it: `dash` drawn, `gap` skipped, from the
    /// first point. Each dash keeps the path's vertices it passes, so a dash across a corner bends there.
    static func dashes(_ path: [SIMD2<Double>], dash: Double, gap: Double) -> [[SIMD2<Double>]] {
        guard path.count >= 2, dash > 0, gap >= 0 else { return [] }
        let edges = path.indices.map { (path[$0], path[($0 + 1) % path.count]) }
        let perimeter = edges.map { simd_distance($0.0, $0.1) }.reduce(0, +)
        var result: [[SIMD2<Double>]] = []
        var start = 0.0
        while start < perimeter - 1e-12 {
            let end = min(start + dash, perimeter)
            var points: [SIMD2<Double>] = []
            var at = 0.0
            for (a, b) in edges {
                let length = simd_distance(a, b)
                defer { at += length }
                guard length > 0, at + length > start, at < end else { continue }
                let from = max(start, at), to = min(end, at + length)
                let p = a + (b - a) * ((from - at) / length), q = a + (b - a) * ((to - at) / length)
                if points.isEmpty || simd_distance(points[points.count - 1], p) > 1e-12 { points.append(p) }
                points.append(q)
            }
            if points.count >= 2 { result.append(points) }
            start += dash + gap
        }
        return result
    }

    /// The small circle on the eye axis: 0.5 deg radius.
    static let axisCircle = stride(from: 0.0, to: 360, by: 10).map { BoundaryDot(rayDeg: $0, eccDeg: 0.5) }

    /// Axis-aligned tangent-space box of a closed outline polygon (its vertices: the lens outline's 5-degree rays,
    /// measured and interpolated, or the rect's rays plus corners). Straight edges between vertices cannot reach
    /// further than their ends, so the vertices bound the drawn shape.
    static func bbox(_ outline: [BoundaryDot]) -> ProjectionBox? {
        guard !outline.isEmpty else { return nil }
        let points = outline.map { dot -> SIMD2<Double> in
            let r = tan(dot.eccDeg * .pi / 180), ray = dot.rayDeg * .pi / 180
            return [r * cos(ray), r * sin(ray)]
        }
        return ProjectionBox(left: -points.map(\.x).min()!, right: points.map(\.x).max()!,
                             up: points.map(\.y).max()!, down: -points.map(\.y).min()!)
    }

    /// The 1:1 band of ALVR's foveated encoding on one axis as fractions of the eye's render (eye UV), from the
    /// raw settings and the render size: the 2r-pixel alignment of FFR.swift:79-89 (in Float, as there), then the
    /// band bounds c0 (1 + s) .. c0 (s - 1) + 1, c0 = (1 - c) / 2, of Shaders.metal:152-157.
    static func band(centerSize: Double, shift: Double, edgeRatio: Double, pixels: Int) -> (lo: Double, hi: Double) {
        let n = Float(pixels), c = Float(centerSize), s = Float(shift), r = Float(edgeRatio)
        guard n > 0, r > 0 else { return (0, 1) }
        let edgeSize = n - c * n
        let centerAligned = 1 - ceil(edgeSize / (r * 2)) * (r * 2) / n
        let edgeAligned = n - centerAligned * n
        let shiftAligned = edgeAligned > 0 ? ceil(s * edgeAligned / (r * 2)) * (r * 2) / edgeAligned : 0
        let c0 = Double(1 - centerAligned) / 2, sa = Double(shiftAligned)
        return (c0 * (1 + sa), c0 * (sa - 1) + 1)
    }

    /// The foveation band as a tangent box of one eye's rendered frustum. Eye UV x runs from the temporal edge
    /// (L: left; R: right, ALVR mirrors the right eye, Shaders.metal:136-140) and y from the top row.
    static func foveationRect(eye: BoundaryDotsEye, frustum: BoundaryDotsFrustum, foveation: ProjectionFoveation,
                              render: ProjectionRender) -> ProjectionBox? {
        let x = band(centerSize: foveation.centerSize.x, shift: foveation.shift.x, edgeRatio: foveation.edgeRatio.x, pixels: render.width)
        let y = band(centerSize: foveation.centerSize.y, shift: foveation.shift.y, edgeRatio: foveation.edgeRatio.y, pixels: render.height)
        let spanX = frustum.left + frustum.right, spanY = frustum.top + frustum.bottom
        let up = frustum.top - y.lo * spanY, down = y.hi * spanY - frustum.top
        switch eye {
        case .left:
            return ProjectionBox(left: frustum.left - x.lo * spanX, right: x.hi * spanX - frustum.left, up: up, down: down)
        case .right:
            return ProjectionBox(left: x.hi * spanX - frustum.right, right: frustum.right - x.lo * spanX, up: up, down: down)
        case .both:
            return nil
        }
    }

    /// Predicted px/deg on the eye axis if `render` pixels span `box` (tools/diag/avp-sharpness.py "centre": the page
    /// prediction at tan 0 inside the 1:1 band, render px over the tan span x pi/180; the lower of h and v).
    static func pxPerDegAxis(render: ProjectionRender, box: ProjectionBox) -> Double {
        min(Double(render.width) / (box.left + box.right), Double(render.height) / (box.up + box.down)) * .pi / 180
    }
}

/// One eye's projection numbers: the bbox of its outline, the foveation rect and px/deg for the frustum and bbox,
/// as overlay text lines and `dots_outline` fields.
struct ProjectionReadout: Equatable {
    let eye: BoundaryDotsEye
    let frustum: ProjectionBox
    let bbox: ProjectionBox
    let fovRect: ProjectionBox?
    let stream: ProjectionStream
    let pxdegFrustum, pxdegBbox: Double

    init?(eye: BoundaryDotsEye, frustum: BoundaryDotsFrustum, outline: [BoundaryDot], stream: ProjectionStream) {
        guard eye != .both, let bbox = ProjectionOverlay.bbox(outline) else { return nil }
        self.eye = eye
        self.frustum = ProjectionBox(frustum)
        self.bbox = bbox
        self.stream = stream
        fovRect = stream.foveation.flatMap {
            ProjectionOverlay.foveationRect(eye: eye, frustum: frustum, foveation: $0, render: stream.render)
        }
        pxdegFrustum = ProjectionOverlay.pxPerDegAxis(render: stream.render, box: self.frustum)
        pxdegBbox = ProjectionOverlay.pxPerDegAxis(render: stream.render, box: bbox)
    }

    private static func list(_ values: [Double], _ format: String, _ separator: String = ",") -> String {
        values.map { String(format: format, locale: Locale(identifier: "en_US_POSIX"), $0) }.joined(separator: separator)
    }

    var bboxDeg: String { Self.list(bbox.degrees, "%.3f") }
    var bboxTan: String { Self.list(bbox.tangents, "%.4f") }
    var fovRectDeg: String { fovRect.map { Self.list($0.degrees, "%.3f") } ?? "off" }
    var foveation: String { stream.foveation?.text ?? "off" }
    var renderPx: String { "\(stream.render.width),\(stream.render.height)" }
    var fovLive: String { stream.live ? "yes" : "no" }
    /// Where the foveation rect comes from: "fov (live)" or "fov <row> (preset, not live)".
    var fovLabel: String { stream.live ? "fov (live)" : "fov \(stream.source) (preset, not live)" }

    var lines: [String] {
        func sides(_ box: ProjectionBox) -> String {
            let d = box.degrees
            return String(format: "L %.1f R %.1f U %.1f D %.1f deg", locale: Locale(identifier: "en_US_POSIX"), d[0], d[1], d[2], d[3])
        }
        let name = eye.rawValue, size = "\(stream.render.width)x\(stream.render.height)"
        return [
            "\(name) bbox \(sides(bbox))  tan \(Self.list(bbox.tangents, "%.3f", "/"))",
            "\(name) \(fovLabel)  rect \(fovRect.map(sides) ?? "off")  \(size)",
            String(format: "%@ px/deg axis: frustum %.1f → bbox %.1f (×%.2f)", locale: Locale(identifier: "en_US_POSIX"),
                   name, pxdegFrustum, pxdegBbox, pxdegBbox / pxdegFrustum),
        ]
    }
}
